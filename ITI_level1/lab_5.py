# 8. Calculate total sale data for last year for each product and show it using a
# Pie chart
# Note: In Pie chart display Number of units sold per year for each product in
# percentage.

products = [
    "Face Cream",
    "Face Wash",
    "ToothPaste",
    "Bathing soap",
    "Shampoo",
    "Moisturizer"
]

sales = [
    df["facecream"].sum(),
    df["facewash"].sum(),
    df["toothpaste"].sum(),
    df["bathingsoap"].sum(),
    df["shampoo"].sum(),
    df["moisturizer"].sum()
]

plt.pie(
    sales,
    labels=products,
    autopct="%1.1f%%"
)

plt.title("Total Sales for Last Year")

plt.show()

