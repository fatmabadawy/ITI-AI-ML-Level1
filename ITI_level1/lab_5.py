# 5. Read face cream and facewash product sales data and show it using the
# bar chart
# The bar chart should display the number of units sold per month for each
# product. Add a separate bar for each product in the same chart.

x = np.arange(len(df["month_number"]))

width = 0.4

plt.bar(
    x - width/2,
    df["facecream"],
    width=width,
    label="Face Cream"
)

